# Steps used (2026-11-02), with mapshaper 0.6 from npm:
#   mapshaper adm2.geojson -simplify 7% keep-shapes -clean -proj +proj=utm +zone=46 +datum=WGS84 -o format=geojson precision=10 proj.json
#   mapshaper proj.json -points inner -o format=geojson inner.json
#   mapshaper proj.json -join div.csv keys=shapeName,shapeName -innerlines where="A.div!=B.div" -o format=geojson divlines.json
#   mapshaper proj.json -dissolve -o format=geojson outline.json
#   python3 build-map.py bd.json ../../assets/js/deshchitro-map.js   (paths below point at the working folder)
