SLUG={'Bogra':'bogura','Brahamanbaria':'brahmanbaria','Chittagong':'chattogram','Comilla':'cumilla',"Cox's Bazar":'coxsbazar','Jessore':'jashore','Barisal':'barishal','Nawabganj':'chapainawabganj','Maulvibazar':'moulvibazar','Jhalokati':'jhalakathi','Netrakona':'netrokona'}
d=json.load(open('/tmp/geo/proj.json')); pts=json.load(open('/tmp/geo/inner.json'))
xs=[];ys=[]
def rings(g):
  if g['type']=='Polygon': return g['coordinates']
  return [r for p in g['coordinates'] for r in p]
for f in d['features']:
  for r in rings(f['geometry']):
    for x,y in r: xs.append(x);ys.append(y)
minx,maxx,miny,maxy=min(xs),max(xs),min(ys),max(ys)
W=600.0; s=W/(maxx-minx); pad=6; H=(maxy-miny)*s
def P(x,y): return ((x-minx)*s+pad,(maxy-y)*s+pad)
out=[]
for f in d['features']:
  n=f['properties']['shapeName']; parts=[]
  for r in rings(f['geometry']):
    pp=[P(x,y) for x,y in r]; seg='M'+' '.join('%.1f,%.1f'%p for p in pp[:-1])+'Z'
    # relative compaction not needed
    parts.append(seg)
  out.append((n,''.join(parts)))
cent={}
for f in pts['features']:
  x,y=f['geometry']['coordinates']; cent[f['properties']['shapeName']]=P(x,y)
assert set(BN)==set(n for n,_ in out)
res={'w':round(W+2*pad),'h':round(H+2*pad),'d':[]}
for n,p in sorted(out):
  key=SLUG.get(n,n.lower().replace(' ','').replace("'",''))
  res['d'].append({'k':key,'bn':BN[n],'en':n,'c':[round(cent[n][0],1),round(cent[n][1],1)],'p':p})
json.dump(res,open(sys.argv[1],'w'),ensure_ascii=False,separators=(',',':'))
print(res['w'],res['h'],len(res['d']))

def lines(fn, closed):
  g=json.load(open(fn)); s=''
  geos=[f['geometry'] for f in g['features']] if 'features' in g else (g['geometries'] if 'geometries' in g else [g])
  for geo in geos:
    if geo['type'] in ('LineString',): ls=[geo['coordinates']]
    elif geo['type']=='MultiLineString': ls=geo['coordinates']
    else: ls=rings(geo)
    for r in ls:
      pp=[P(x,y) for x,y in r]
      if closed: pp=pp[:-1]
      s+='M'+' '.join('%.1f,%.1f'%p for p in pp)+('Z' if closed else '')
  return s
res['div']=lines('/tmp/geo/divlines.json',False)
res['out']=lines('/tmp/geo/outline.json',True)
