/**
 * Link to the contact page if one exists, else plain text.
 *
 * @return string HTML.
 */
function meeha_policy_contact_html() {
	foreach ( array( 'contact', 'contact-us', 'jogajog', 'yogayog' ) as $slug ) {
		$p = get_page_by_path( $slug );
		if ( $p && 'publish' === $p->post_status ) {
			return '<a href="' . esc_url( get_permalink( $p ) ) . '">যোগাযোগ পাতা</a>';
		}
	}
	return 'যোগাযোগ পাতা';
}

