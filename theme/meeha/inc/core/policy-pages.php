/**
 * Create the two policy pages if their slugs do not exist yet. Never overwrites.
 *
 * @return string[] Titles created.
 */
function meeha_policy_pages_ensure() {
	$made  = array();
	$pages = array(
		'editorial-policy'   => array( 'সম্পাদকীয় নীতি', 'meeha_policy_editorial_html' ),
		'corrections-policy' => array( 'সংশোধন নীতি', 'meeha_policy_corrections_html' ),
	);
	foreach ( $pages as $slug => $def ) {
		$exists = get_posts(
			array(
				'post_type'      => 'page',
				'name'           => $slug,
				'post_status'    => 'any',
				'posts_per_page' => 1,
				'fields'         => 'ids',
				'no_found_rows'  => true,
			)
		);
		if ( $exists || get_page_by_path( $slug ) ) {
			continue;
		}
		$id = wp_insert_post(
			array(
				'post_type'      => 'page',
				'post_status'    => 'publish',
				'post_title'     => $def[0],
				'post_name'      => $slug,
				'post_content'   => call_user_func( $def[1] ),
				'comment_status' => 'closed',
				'ping_status'    => 'closed',
			),
			true
		);
		if ( $id && ! is_wp_error( $id ) ) {
			$made[] = $def[0];
		}
	}
	if ( $made ) {
		wp_cache_delete( 'meeha_policy_url', 'meeha' );
	}
	return $made;
}
