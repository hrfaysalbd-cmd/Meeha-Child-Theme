/**
 * Pick a library topic for a category by slug / name; '' = generic.
 *
 * @param WP_Term $c Category.
 * @return string
 */
function meeha_samples_topic_for( $c ) {
	$hay = $c->slug . ' ' . $c->name;
	$map = array(
		'indigenous'  => array( 'indigenous', 'আদিবাসী' ),
		'heritage'    => array( 'history', 'heritage', 'ইতিহাস', 'ঐতিহ্য' ),
		'humanwall'   => array( 'human-wall', 'মানব দেয়াল' ),
		'poems'       => array( 'sahityaloka', 'poem', 'kobita', 'সাহিত্যলোক', 'কবিতা' ),
		'story'       => array( 'story', 'golpo', 'গল্প' ),
		'essay'       => array( 'essay', 'probondho', 'প্রবন্ধ' ),
		'folk'        => array( 'folk', 'লোকসংস্কৃতি', 'লোকজ' ),
		'books'       => array( 'book', 'বই' ),
		'translation' => array( 'translat', 'onubad', 'অনুবাদ' ),
		'interview'   => array( 'interview', 'sakkhatkar', 'সাক্ষাৎকার' ),
	);
	foreach ( $map as $topic => $needles ) {
		foreach ( $needles as $n ) {
			if ( false !== mb_stripos( $hay, $n ) ) {
				return $topic;
			}
		}
	}
	return '';
}

